  objects('Objects', Icons.lightbulb_outlined, _objects),
  symbols('Symbols', Icons.favorite_outline, _symbols),
  flags('Flags', Icons.flag_outlined, _flags);

  const EmojiCategory(this.label, this.icon, this.emojis);

  final String label;
  final IconData icon;
  final List<EmojiData> emojis;
}

