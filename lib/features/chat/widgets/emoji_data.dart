import 'package:flutter/material.dart';

/// One emoji plus the text used for searching it.
class EmojiData {
  const EmojiData(
    this.emoji,
    this.name, {
    this.keywords = const <String>[],
    this.skinnable = false,
  });

  /// The emoji characters (may be a ZWJ sequence).
  final String emoji;

  /// Short CLDR-style name (lowercase words).
  final String name;

  /// Extra search terms (synonyms, categories).
  final List<String> keywords;

  /// Whether a skin-tone modifier can be appended to this emoji.
  final bool skinnable;

  /// All tokens matched by the search field.
  String get searchText {
    final StringBuffer buffer = StringBuffer(name);
    for (final String keyword in keywords) {
      buffer.write(' $keyword');
    }
    return buffer.toString();
  }
}

